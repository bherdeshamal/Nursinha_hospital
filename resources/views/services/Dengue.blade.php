                                        <li>&nbsp&nbsp&nbsp 4. Taiwan</li>
                                        <li>&nbsp&nbsp&nbsp 5. The Pacific Islands</li>
                                        
                                    </ul>

                                </ol>
                               
                        
                        <p style="text-align :justify; font-size:16px;">Most cases in the United States occur in people who contracted the infection while traveling abroad. But the risk is increasing for people living along the Texas-Mexico border and in other parts of the southern United States. In 2009, an outbreak of dengue fever was identified in Key West, Fla.
                            Dengue fever is transmitted by the bite of an Aedes mosquito infected with a dengue virus. The mosquito becomes infected when it bites a person with dengue virus in their blood. It can’t be spread directly from one person to another person.</p> 
                        </br>

                        <font size="5px" ; color="#C71585">Symptoms of Dengue Fever</font> 
                                <p style="text-align : justify; font-size:16px;">Symptoms, which usually begin four to six days after infection and last for up to 10 days, may include</p>
                                </br>

                        <ol>
                     <ul>
                         <li>&nbsp&nbsp&nbsp 1. Sudden, high fever</li>
                         <li>&nbsp&nbsp&nbsp 2. Severe headaches</li>
                         <li>&nbsp&nbsp&nbsp 3. Pain behind the eyes</li>
                         <li>&nbsp&nbsp&nbsp 4. Severe joint and muscle pain</li>
                         <li>&nbsp&nbsp&nbsp 5. Fatigue,Nausea, Vomiting</li>
                        
                     </ul>

                 </ol>
                </br>

               
                        
                <p style="text-align :justify; font-size:16px;">Sometimes, symptoms are mild and can be mistaken for those of the flu or another viral infection. Younger children and people who have never had the infection before tend to have milder cases than older children and adults. However, serious problems can develop. These include dengue hemorrhagic fever, a rare complication characterized by high fever, damage to lymph and blood vessels, bleeding from the nose and gums, enlargement of the liver, and failure of the circulatory system. The symptoms may progress to massive bleeding, shock, and death. This is called dengue shock syndrome (DSS).

People with weakened immune systems as well as those with a second or subsequent dengue infection are believed to be at greater risk for developing dengue hemorrhagic fever.</p>
            </br>

            <font size="5px" ; color="#C71585">Diagnosing Dengue Fever</font> 
             <p style="text-align :justify; font-size:16px;">   Doctors can diagnose dengue infection with a blood test to check for the virus or antibodies to it. If you become sick after traveling to a tropical area, let your doctor know. This will allow your doctor to evaluate the possibility that your symptoms were caused by a dengue infection.</p>
            </br>

            <font size="5px" ; color="#C71585">Treatment for Dengue Fever</font> 
             <p style="text-align :justify; font-size:16px;"> There is no specific medicine to treat dengue infection. If you think you may have dengue fever, you should use pain relievers with acetaminophen and avoid medicines with aspirin, which could worsen bleeding. You should also rest, drink plenty of fluids, and see your doctor. If you start to feel worse in the first 24 hours after your fever goes down, you should get to a hospital immediately to be checked for complications.</p>
            </br>

