                        <font size="5px" ; color="#C71585">Overview</font> 
                                <p style="text-align : justify; font-size:16px;">Dengue (pronounced DENgee) fever is a painful, debilitating mosquito-borne disease caused by any one of four closely related dengue viruses. These viruses are related to the viruses that cause West Nile infection and yellow fever.
                                        An estimated 390 million dengue infections occur worldwide each year, with about 96 million resulting in illness. Most cases occur in tropical areas of the world, with the greatest risk occurring in:</p>
                                </br>

                                <ol>
                                    <ul>
                                        <li>&nbsp&nbsp&nbsp 1. The Indian subcontinent</li>
                                        <li>&nbsp&nbsp&nbsp 2. Southeast Asia</li>
