            <font size="5px" ; color="#C71585">Preventing Dengue Fever</font> 
             <p style="text-align :justify; font-size:16px;"> There is no vaccine to prevent dengue fever. The best way to prevent the disease is to prevent bites by infected mosquitoes, particularly if you are living in or traveling to a tropical area. This involves protecting yourself and making efforts to keep the mosquito population down.
To protect yourself:</p>
            </br>
                <ol>
                     <ul>
                         <li>&nbsp&nbsp&nbsp 1. Stay away from heavily populated residential areas, if possible.</li>
                         <li>&nbsp&nbsp&nbsp 2. Use mosquito repellents, even indoors.</li>
                         <li>&nbsp&nbsp&nbsp 3. When outdoors, wear long-sleeved shirts and long pants tucked into socks.</li>
                         <li>&nbsp&nbsp&nbsp 4. When indoors, use air conditioning if available.</li>
                         <li>&nbsp&nbsp&nbsp 5. Make sure window and door screens are secure and free of holes. If sleeping areas are not screened or air conditioned, use mosquito nets.</li>
