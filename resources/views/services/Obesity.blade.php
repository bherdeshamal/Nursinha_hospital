                        <font size="5px" ; color="#C71585">Overview</font> 
                                <p style="text-align : justify; font-size:16px;">Obesity is a complex disease involving an excessive amount of body fat. Obesity isn't just a cosmetic concern. It's a medical problem that increases the risk of other diseases and health problems, such as heart disease, diabetes, high blood pressure and certain cancers.</p>
                                 </br>
                                 <p style="text-align : justify; font-size:16px;">There are many reasons why some people have difficulty losing weight. Usually, obesity results from inherited, physiological and environmental factors, combined with diet, physical activity and exercise choices.</p>

                                 </br>
                                 <p style="text-align : justify; font-size:16px;">The good news is that even modest weight loss can improve or prevent the health problems associated with obesity. A healthier diet, increased physical activity and behavior changes can help you lose weight. Prescription medications and weight-loss procedures are additional options for treating obesity.</p>
                                </br>
                             
            <font size="5px" ; color="#C71585">Symptoms </font> 
</br>
            <p style="text-align :justify; font-size:16px;"> Body mass index (BMI) is often used to diagnose obesity. To calculate BMI, multiply weight in pounds by 703, divide by height in inches and then divide again by height in inches. Or divide weight in kilograms by height in meters squared.</p>
                </br> 
                <p style="text-align :justify; font-size:16px;">For most people, BMI provides a reasonable estimate of body fat. However, BMI doesn't directly measure body fat, so some people, such as muscular athletes, may have a BMI in the obesity category even though they don't have excess body fat.

Many doctors also measure a person's waist circumference to help guide treatment decisions. Weight-related health problems are more common in men with a waist circumference over 40 inches (102 centimeters) and in women with a waist measurement over 35 inches (89 centimeters).</p>
       </br>

                  <font size="5px" ; color="#C71585">Causes</font> 
                        </br>
                        <p style="text-align :justify; font-size:16px;"> Although there are genetic, behavioral, metabolic and hormonal influences on body weight, obesity occurs when you take in more calories than you burn through normal daily activities and exercise. Your body stores these excess calories as fat.

In the United States, most people's diets are too high in calories — often from fast food and high-calorie beverages. People with obesity might eat more calories before feeling full, feel hungry sooner, or eat more due to stress or anxiety.</p>
            
                            
                </br>
                <p style="text-align :justify; font-size:16px;"> Many people who live in Western countries now have jobs that are much less physically demanding, so they don't tend to burn as many calories at work. Even daily activities use fewer calories, courtesy of conveniences such as remote controls, escalators, online shopping and drive-through banks.</p>
            

                
